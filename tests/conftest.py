class UiServed(NamedTuple):
    """What `ui_cmd` handed the server: the ASGI app, and the address of
    the socket it was told to serve on."""
    app: object
    address: tuple  # (host, port) as the kernel reports it, post-bind


@pytest.fixture
def stub_ui_server(monkeypatch):
    """Stop `ui_cmd` short of actually serving, and record what it was
    about to serve.

    **This lives here because it used to live in two places.** Both
    `test_cli.py` and `test_console_address.py` had grown their own copy
    of a `uvicorn.run` monkeypatch, and an earlier change -- which moved `ui_cmd`
    off `uvicorn.run` onto `uvicorn.Server.run(sockets=...)` -- was fixed
    against one of them. The other copy went on patching a function
    nothing called, so its two tests started a real web server and the
    suite hung forever on a port that never closes. One copy, one place.

    Note the bind in `ui_cmd` is REAL and happens before this stub is
    reached; that is the whole point of #169. A test that does not care
    which port it gets should pass `--port 0` and let the kernel pick.
    """
    uvicorn = pytest.importorskip("uvicorn")
    served: list[UiServed] = []

    def _fake_run(self, sockets=None):
        first = sockets[0] if sockets else None
        served.append(UiServed(self.config.app,
                               first.getsockname()[:2] if first is not None else None))
        # The real server closes these on shutdown, so the stub must too
        # -- otherwise the session leaks a listening socket per test.
        for sock in sockets or ():
            sock.close()

    monkeypatch.setattr(uvicorn.Server, "run", _fake_run)
    return served


