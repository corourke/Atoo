"""Shared fixtures.

The one thing worth explaining here is `stub_build`. Since #29 retired the
deterministic compile path, **every** plan comes from a model, so a CLI
test that wants a plan either talks to a provider (it must not) or stubs
one. Before #29 these tests passed `--no-ai` and got a compiled plan;
that flag and the code behind it are gone.

Stubbing at `generate_plan` rather than at the HTTP layer is deliberate:
these are tests about what `build` does with a plan -- where it writes it,
what it verifies, what it prints -- not about how a model produced one.
The tests that *are* about the provider boundary (streaming, truncated
replies, constrained decoding, the critic's second call) stub the provider
itself, in `test_generate_and_verify_cli.py`, and are unaffected by this.
"""

