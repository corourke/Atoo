FIXTURES = Path(__file__).parent / "fixtures"

# Real plans for four real shows, 9 to 38 channels. Generated by the
# deterministic compiler at `origin/main` immediately before #29 deleted
# it, so the tests that assert on their contents still assert against the
# same bytes they were written against.
REAL_PLANS = json.loads((FIXTURES / "real_plans.json").read_text())


