@pytest.fixture
def stub_build(monkeypatch):
    """Make `atoo build` produce a known plan with no model.

    Usage:

        def test_something(stub_build, tmp_path):
            plan = stub_build("smallband")
            main(["build", "--console-model", "wing-compact", "--input", ..., "--conventions", ..., ...])

    Returns the plan it will produce, so a test can assert against it
    without reaching back into the fixture file.
    """

    def use(name: str = "smallband") -> dict:
        plan = copy.deepcopy(REAL_PLANS[name])

        # `build` calls provider_from_env() before generate_plan(); it
        # never touches the result when generate_plan is stubbed, so an
        # opaque object is enough and keeps the stub honest about not
        # pretending to be a provider.
        monkeypatch.setattr("atoo.cli.provider_from_env", lambda: object())
        # No fix-up round: the stand-in provider has no model to send a
        # refused plan back to, and a test of a plan verify refuses (the
        # touringband Matrix) is about that plan, not about a second one.
        # tests/test_fixup_round.py covers the round with a real stub.
        monkeypatch.setenv("ATOO_AI_FIXUP_ROUNDS", "0")

        def fake_generate_plan(*args, **kwargs):
            built = copy.deepcopy(plan)
            # The real `generate_plan` records which console the
            # plan was built for, and `verify`/`apply` read it back out of
            # the file. A stub that skipped it would make every CLI test
            # exercise the no-model path instead of the one users are on.
            if kwargs.get("console_model"):
                built.setdefault("meta", {})["console_model"] = kwargs["console_model"]
            return built

        monkeypatch.setattr("atoo.generate.generate_plan", fake_generate_plan)
        return plan

    return use


def require_fastapi_testclient():
    """`fastapi.testclient`, or skip -- **catching `RuntimeError` as well as
    `ImportError`**, which is the whole point of this living here.

    FastAPI's TestClient is built on Starlette's, which needs an HTTP
    client. When it cannot find one, current Starlette raises
    ``RuntimeError`` *at import time*, not ``ImportError``::

        RuntimeError: The starlette.testclient module requires the httpx2 package

    `pytest.importorskip` only catches `ImportError`, so that escaped as a
    collection error and the whole suite ran **nothing at all** -- the worst
    available outcome, and indistinguishable at a glance from a broken
    checkout. `docs/user/install.md` carried a hand-install note for it.

    Two separate test modules had reproduced the same broken guard, and a
    third would have. A missing optional test dependency skips the tests
    that need it; that is all this does.
    """
    import pytest

    try:
        module = pytest.importorskip("fastapi.testclient")
    except RuntimeError as exc:  # pragma: no cover -- needs the dependency absent
        pytest.skip(f"fastapi's TestClient is unusable here: {exc}",
                    allow_module_level=True)
    return types.SimpleNamespace(TestClient=_local_test_client(module.TestClient))


def _local_test_client(base):
    """Starlette's TestClient calls itself `testclient` at `testserver`,
    which is neither a loopback client nor a loopback Host -- so every
    endpoint that opens a path the request names (`webui._local_only`) would refuse it as a machine on the LAN. The
    suite models the page opened on the laptop itself, so that is the
    default here; a test about the LAN passes `client=` and a `host`
    header of its own, as `test_webui_filebrowser.py` does."""

    class LocalTestClient(base):
        def __init__(self, app, *args, **kwargs):
            kwargs.setdefault("client", ("127.0.0.1", 50000))
            kwargs.setdefault("base_url", "http://127.0.0.1:8420")
            super().__init__(app, *args, **kwargs)

    return LocalTestClient


