# `examples/` is the maintainer's, not the test suite's
# --------------------------------------------------------------------------
#
# On 2026-09-23 the maintainer rebuilt `examples/touringband/` from an edited input
# list and a new `instructions.md`. The rebuild was correct -- `verify --show`
# reported no findings and every check in `verify-rebuild.sh` passed -- and it
# turned NINE tests red, in three modules, without a line of `atoo`
# changing. They had been reading his working files as though they were
# fixtures: one needed LCL to be full (the monitors moved to AES50-A), one
# named the two conditions it expected in `watch.json` (the rebuild drafted
# nineteen), one wanted critic findings in the pre-#18 shape (the rebuild
# wrote them in the current one).
#
# So the rule, and this is the thing that enforces it: **no test may read a
# file anywhere under `examples/` unless its subject IS that file**, in which
# case it is marked `example_guard` and asserts that the file is VALID, never
# what is in it -- `test_the_example_bundle_still_verifies_clean` and
# `test_every_shipped_example_plan_still_verifies_clean` are the shape that
# stays.
#
# The guard first covered `examples/touringband/` only. Since 2026-09-29
# (the maintainer: "move the test fixtures into tests/fixtures") it
# covers the whole directory -- the show bundles, `amend-demo/`,
# `channel_presets/`, `console-runs/` and the loose files alike. A test that
# needs one of them reads a frozen copy under `tests/fixtures/`, listed with
# its provenance in `tests/fixtures/README.md`.
#
# Enforced at runtime rather than by reading the test source, because the
# coupling arrives by every route: a module-level constant, a `--plan` path
# handed to `main()`, a fixture two files away. Anything that opens the file
# is caught, however the path was spelled.

REPO_ROOT = Path(__file__).resolve().parents[1]

LIVING_EXAMPLE_BUNDLES = (REPO_ROOT / "examples",)


class LivingExampleRead(BaseException):
    """A test touched a file under `examples/`, which is a living example.

    Deliberately a `BaseException`: this travels out through `atoo`
    code that catches `OSError` and `ValueError` around its own file
    reads, and a guard a product `except` clause can swallow is a guard
    that reports nothing.
    """


_GUARD_SUSPENDED = [False]
_GUARD_INSTALLED = [False]


def _living_example(path) -> "Path | None":
    """The bundle file `path` points at, or None -- cheap enough to sit in
    front of every `open()` in the suite."""
    try:
        raw = os.fspath(path)
    except TypeError:
        return None                      # a file descriptor, not a path
    if isinstance(raw, bytes):
        try:
            raw = raw.decode()
        except UnicodeDecodeError:
            return None
    if "examples" not in raw:
        return None
    candidate = Path(raw)
    if not candidate.is_absolute():
        candidate = Path.cwd() / candidate
    candidate = Path(os.path.normpath(str(candidate)))
    for bundle in LIVING_EXAMPLE_BUNDLES:
        if candidate == bundle or bundle in candidate.parents:
            return candidate
    return None


def _refuse(path: Path) -> None:
    try:
        shown = path.relative_to(REPO_ROOT)
    except ValueError:                   # pragma: no cover -- outside the repo
        shown = path
    raise LivingExampleRead(
        f"this test touched {shown}, which is a LIVING EXAMPLE, not a fixture.\n"
        "\n"
        "Everything under examples/ is the maintainer's: he edits and rebuilds the "
        "bundles between shows, and the desk captures and presets there are his "
        "working material. A test that depends on what is in one -- a channel "
        "number, a bus name, a socket, a watch-condition id, how many DI channels "
        "there are -- goes red on his work rather than on a regression. Nine did, "
        "on 2026-09-23.\n"
        "\n"
        "Give this test the fixture it actually needs: build it in the test (say "
        "what it depends on -- 'a plan whose LCL outputs are all claimed' -- and "
        "construct that), or freeze a copy under tests/fixtures/ the way "
        "tests/fixtures/applied-show.plan.json is frozen.\n"
        "\n"
        "If the test's SUBJECT really is the shipped file -- that it still "
        "verifies, that it still answers the audit's socket rules -- then mark it "
        "@pytest.mark.example_guard and assert that it is VALID, never "
        "what is in it. See tests/conftest.py for the whole rule."
    )


def pytest_configure(config):
    """Install the guard for the whole session, collection included -- the
    read that started this was a module-level constant."""
    import builtins
    import io
    import pathlib

    if _GUARD_INSTALLED[0]:              # a second configure would double-wrap
        return
    _GUARD_INSTALLED[0] = True

    def _wrap(original):
        def guarded(file, *args, **kwargs):
            if not _GUARD_SUSPENDED[0]:
                hit = _living_example(file)
                if hit is not None:
                    _refuse(hit)
            return original(file, *args, **kwargs)
        return guarded

    def _wrap_method(original):
        def guarded(self, *args, **kwargs):
            if not _GUARD_SUSPENDED[0]:
                hit = _living_example(self)
                if hit is not None:
                    _refuse(hit)
            return original(self, *args, **kwargs)
        return guarded

    # `builtins.open` and `io.open` are the same function but two separate
    # names, and `pathlib` reaches for the latter -- patch both. The Path
    # methods are patched as well so the guard does not depend on which of
    # them this interpreter routes through.
    builtins.open = _wrap(builtins.open)
    io.open = _wrap(io.open)
    for name in ("open", "read_text", "read_bytes"):
        setattr(pathlib.Path, name, _wrap_method(getattr(pathlib.Path, name)))


@pytest.fixture
def whole_repository_sweep():
    """Stand the guard down for a check that walks EVERY tracked file.

    The one honest exception that is not an `example_guard`: a repo-wide
    hygiene sweep (merge-conflict markers, encodings) reads the bundle
    because it reads everything, and depends on nothing in it. Nothing
    else may use it -- a test that wants one file out of the bundle is the
    case the guard exists for.

    A fixture rather than an importable context manager on purpose. This
    file is loaded by pytest as `conftest` and is importable as
    `tests.conftest`, which are two module objects with two copies of the
    flag below; the first version of this was imported the second way and
    suspended a guard nothing was reading.
    """
    @contextlib.contextmanager
    def sweeping(why: str):
        assert why  # a caller has to say what it is sweeping for
        previous, _GUARD_SUSPENDED[0] = _GUARD_SUSPENDED[0], True
        try:
            yield
        finally:
            _GUARD_SUSPENDED[0] = previous

    return sweeping


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_protocol(item, nextitem):
    """Stand the guard down for a test whose subject is the bundle --
    around the whole protocol, so a module- or session-scoped fixture set
    up on its behalf is covered too."""
    suspended = item.get_closest_marker("example_guard") is not None
    previous, _GUARD_SUSPENDED[0] = _GUARD_SUSPENDED[0], suspended
    try:
        yield
    finally:
        _GUARD_SUSPENDED[0] = previous
